  const types = ['commercial', 'residential', 'mixed-use'];
  const cities = ['Jakarta', 'Bali', 'Surabaya', 'Bandung'];
  
  const type = types[Math.floor(Math.random() * types.length)];
  const city = cities[Math.floor(Math.random() * cities.length)];
  
  const targetAmount = (Math.floor(Math.random() * 50) + 10) * 100000;
  const currentAmount = Math.floor(Math.random() * targetAmount);
  const roi = (Math.floor(Math.random() * 10) + 8) + Math.random();
  const duration = (Math.floor(Math.random() * 36) + 12);
  const minInvestment = (Math.floor(Math.random() * 10) + 1) * 1000;
  
  // End date in the future (30-60 days from now)
  const endDate = new Date();
