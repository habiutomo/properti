// Function to get a random image from a category
export const getRandomImage = (category: 'property' | 'interior' | 'investment' | 'virtualTour' = 'property') => {
  switch (category) {
    case 'property':
      return propertyImages[Math.floor(Math.random() * propertyImages.length)];
    case 'interior':
      return interiorImages[Math.floor(Math.random() * interiorImages.length)];
    case 'investment':
      return investmentImages[Math.floor(Math.random() * investmentImages.length)];
    case 'virtualTour':
      return virtualTourImages[Math.floor(Math.random() * virtualTourImages.length)];
    default:
      return propertyImages[0];
  }
};

// Generate mock property data
export const generateMockProperty = (id: number) => {
  const types = ['house', 'apartment', 'land', 'commercial'];
  const cities = ['Bali', 'Jakarta', 'Surabaya', 'Bandung', 'Yogyakarta'];
  const statuses = ['available', 'sold', 'rented'];
  const purposes = ['sale', 'rent'];
  
  const type = types[Math.floor(Math.random() * types.length)];
  const city = cities[Math.floor(Math.random() * cities.length)];
  const status = statuses[Math.floor(Math.random() * statuses.length)];
  const purpose = purposes[Math.floor(Math.random() * purposes.length)];
  
  const bedrooms = type === 'land' ? 0 : Math.floor(Math.random() * 5) + 1;
  const bathrooms = type === 'land' ? 0 : Math.floor(Math.random() * 4) + 1;
  const area = Math.floor(Math.random() * 3000) + 500;
  
  let price;
  if (purpose === 'sale') {
    price = Math.floor(Math.random() * 2000000) + 500000;
  } else {
    price = Math.floor(Math.random() * 5000) + 500;
  }
  
  return {
    id,
    title: `${['Modern', 'Luxury', 'Cozy', 'Spacious'][Math.floor(Math.random() * 4)]} ${type === 'land' ? 'Land' : type === 'commercial' ? 'Office Space' : type === 'apartment' ? 'Apartment' : 'House'}`,
    description: "This beautiful property offers modern amenities and a prime location. Perfect for families looking for comfort and convenience. Close to schools, shopping centers, and parks.",
    price: price.toString(),
    address: `${Math.floor(Math.random() * 100) + 1} Main Street`,
    city,
    country: "Indonesia",
    propertyType: type,
    purpose,
    bedrooms,
    bathrooms,
    area: area.toString(),
    userId: 1,
    hasVirtualTour: Math.random() > 0.5,
    featuredImage: getRandomImage('property'),
    status,
    createdAt: new Date(),
  };
};

// Generate mock investment project
